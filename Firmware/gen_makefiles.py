"""Regenerate the Atmel Studio style Debug/Release Makefiles for the firmware.

Microchip Studio rewrites these itself when you build in the IDE. This script keeps
the command-line build (Firmware/build.ps1) in step when sources change: the source
list comes from the <Compile Include> items in ClearHPGL_Firmware.cppproj.

    python Firmware/gen_makefiles.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
PROJ = HERE / "ClearCoreFirmware"
NAME = "ClearHPGL_Firmware"

TC = r"C:\Program Files (x86)\Atmel\Studio\7.0\toolchain\arm\arm-gnu-toolchain\bin"
PACKS = r"C:\Program Files (x86)\Atmel\Studio\7.0\Packs"
CC = f"$(QUOTE){TC}\\arm-none-eabi-gcc.exe$(QUOTE)"
CXX = f"$(QUOTE){TC}\\arm-none-eabi-g++.exe$(QUOTE)"
DEPS = '-MD -MP -MF "$(@:%.o=%.d)" -MT"$(@:%.o=%.d)" -MT"$(@:%.o=%.o)"   -o "$@" "$<" '

CONFIGS = {
    "Debug": {"define": "-DDEBUG", "cg": "-g3 ", "cxxg": "-g2 "},
    "Release": {"define": "-DNDEBUG", "cg": "", "cxxg": ""},
}


def sources():
    text = (PROJ / f"{NAME}.cppproj").read_text(encoding="utf-8")
    items = re.findall(r'<Compile Include="([^"]+)"', text)
    return [s.replace("\\", "/") for s in items if s.endswith((".c", ".cpp"))]


def obj(src):
    return re.sub(r"\.(c|cpp)$", ".o", src)


def block(var, items):
    return f"{var} +=  \\\n" + " \\\n".join(items) + "\n\n"


def makefile(cfg, opts):
    srcs = sources()
    objs = [obj(s) for s in srcs]
    deps = [o[:-2] + ".d" for o in objs]
    subdirs = sorted({str(pathlib.PurePosixPath(s).parent) for s in srcs} - {"."})
    c_inc = (f'-I"{PACKS}\\atmel\\SAME53_DFP\\1.1.118\\include" -I"{PACKS}\\arm\\CMSIS\\4.5.0\\CMSIS\\Include" '
             f'-I"{PACKS}\\arm\\CMSIS\\5.4.0\\CMSIS\\Core\\Include"')
    cxx_inc = (f'-I"{PACKS}\\arm\\CMSIS\\4.5.0\\CMSIS\\Include" -I"{PACKS}\\atmel\\SAME53_DFP\\1.1.118\\include" '
               '-I"../../../libClearCore/inc" -I"../../../LwIP/LwIP/src/include" -I"../../../LwIP/LwIP/port/include" '
               f'-I"{PACKS}\\arm\\CMSIS\\5.4.0\\CMSIS\\Core\\Include"')
    out = [
        "################################################################################\n",
        "# Generated by Firmware/gen_makefiles.py (Atmel Studio layout). Microchip Studio\n",
        "# regenerates this file when building in the IDE.\n",
        "################################################################################\n\n",
        "SHELL := cmd.exe\nRM := rm -rf\n\nUSER_OBJS :=\n\nLIBS := \nPROJ := \n\n",
        "O_SRCS := \nC_SRCS := \nS_SRCS := \nS_UPPER_SRCS := \nOBJ_SRCS := \nASM_SRCS := \n",
        "PREPROCESSING_SRCS := \nOBJS := \nOBJS_AS_ARGS := \nC_DEPS := \nC_DEPS_AS_ARGS := \n",
        "EXECUTABLES := \nOUTPUT_FILE_PATH :=\nOUTPUT_FILE_PATH_AS_ARGS :=\nAVR_APP_PATH :=$$$AVR_APP_PATH$$$\n",
        'QUOTE := "\nADDITIONAL_DEPENDENCIES:=\nOUTPUT_FILE_DEP:=\nLIB_DEP:=\nLINKER_SCRIPT_DEP:=\n\n',
        "# Every subdirectory with source files must be described here\n",
        "SUBDIRS :=  \\\n" + " \\\n".join(f"../{d}/" for d in subdirs) + "\n\n\n",
        block("C_SRCS", [f"../{s}" for s in srcs]),
        block("OBJS", objs),
        block("OBJS_AS_ARGS", objs),
        block("C_DEPS", deps),
        block("C_DEPS_AS_ARGS", deps),
        f"OUTPUT_FILE_PATH +={NAME}.elf\n\nOUTPUT_FILE_PATH_AS_ARGS +={NAME}.elf\n\n",
        "ADDITIONAL_DEPENDENCIES:=\n\nOUTPUT_FILE_DEP:= ./makedep.mk\n\n",
        f"LIB_DEP+=  \\\n../../../libClearCore/{cfg}/libClearCore.a \\\n../../../LwIP/{cfg}/libLwIP.a\n\n",
        "LINKER_SCRIPT_DEP+=  \\\n../Device_Startup/flash_without_bootloader.ld \\\n"
        "../Device_Startup/flash_with_bootloader.ld \\\n../Device_Startup/same53n19a_flash.ld \\\n"
        "../Device_Startup/same53n19a_sram.ld\n\n\n",
    ]
    for s, o in zip(srcs, objs):
        out.append(f"{o}: ../{s}\n\t@echo Building file: $<\n\t@echo Invoking: ARM/GNU C Compiler : 6.3.1\n")
        if s.endswith(".c"):
            out.append(f"\t{CC}  -x c -mthumb -D__SAME53N19A__ {opts['define']}  {c_inc}  -O3 -ffunction-sections "
                       f"-fdata-sections {opts['cg']}-Wall -mcpu=cortex-m4 -c -std=gnu99 -mfloat-abi=hard "
                       f"-mfpu=fpv4-sp-d16 {DEPS}\n")
        else:
            out.append(f"\t{CXX} -mthumb -D__SAME53N19A__ {opts['define']}  {cxx_inc}  -O3 -ffunction-sections "
                       f"-fno-rtti -fno-exceptions {opts['cxxg']}-Wall -mcpu=cortex-m4 -c -mfloat-abi=hard "
                       f"-mfpu=fpv4-sp-d16 {DEPS}\n")
        out.append("\t@echo Finished building: $<\n\t\n\n")
    objcopy = f'"{TC}\\arm-none-eabi-objcopy.exe"'
    out += [
        "ifneq ($(MAKECMDGOALS),clean)\nifneq ($(strip $(C_DEPS)),)\n-include $(C_DEPS)\nendif\nendif\n\n",
        "# All Target\nall: $(OUTPUT_FILE_PATH) $(ADDITIONAL_DEPENDENCIES)\n\n",
        "$(OUTPUT_FILE_PATH): $(OBJS) $(USER_OBJS) $(OUTPUT_FILE_DEP) $(LIB_DEP) $(LINKER_SCRIPT_DEP)\n",
        "\t@echo Building target: $@\n\t@echo Invoking: ARM/GNU Linker : 6.3.1\n",
        f'\t{CXX} -o$(OUTPUT_FILE_PATH_AS_ARGS) $(OBJS_AS_ARGS) $(USER_OBJS) $(LIBS) -mthumb '
        f'-Wl,-Map="{NAME}.map" --specs=rdimon.specs -Wl,--start-group -lm -larm_cortexM4lf_math -lClearCore '
        f'-lLwIP  -Wl,--end-group -L"../Device_Startup" -L"{PACKS}\\arm\\CMSIS\\4.5.0\\CMSIS\\Lib\\GCC" '
        f'-L"..\\Device_Startup" -L"..\\..\\..\\libClearCore\\{cfg}" -L"..\\..\\..\\LwIP\\{cfg}"  '
        "-Wl,--gc-sections -mcpu=cortex-m4 -T../Device_Startup/flash_with_bootloader.ld -mfloat-abi=hard "
        "-mfpu=fpv4-sp-d16  \n",
        "\t@echo Finished building target: $@\n",
        f'\t{objcopy} -O binary "{NAME}.elf" "{NAME}.bin"\n',
        f'\t{objcopy} -O ihex -R .eeprom -R .fuse -R .lock -R .signature  "{NAME}.elf" "{NAME}.hex"\n',
        f'\t{objcopy} -j .eeprom --set-section-flags=.eeprom=alloc,load --change-section-lma .eeprom=0 '
        f'--no-change-warnings -O binary "{NAME}.elf" "{NAME}.eep" || exit 0\n',
        f'\t"{TC}\\arm-none-eabi-objdump.exe" -h -S "{NAME}.elf" > "{NAME}.lss"\n',
        f'\t{objcopy} -O srec -R .eeprom -R .fuse -R .lock -R .signature  "{NAME}.elf" "{NAME}.srec"\n',
        f'\t"{TC}\\arm-none-eabi-size.exe" "{NAME}.elf"\n\t\n\n',
        "# Other Targets\nclean:\n\t-$(RM) $(OBJS_AS_ARGS) $(EXECUTABLES)  \n\t-$(RM) $(C_DEPS_AS_ARGS)   \n",
        f'\trm -rf "{NAME}.elf" "{NAME}.a" "{NAME}.hex" "{NAME}.bin" "{NAME}.lss" "{NAME}.eep" '
        f'"{NAME}.map" "{NAME}.srec"\n\t',
    ]
    return "".join(out)


def makedep():
    lines = ["################################################################################\n",
             "# Automatically-generated file. Do not edit or delete the file\n",
             "################################################################################\n\n"]
    lines += [s.replace("/", "\\") + "\n\n" for s in sources()]
    return "".join(lines)


def main():
    for cfg, opts in CONFIGS.items():
        d = PROJ / cfg
        d.mkdir(exist_ok=True)
        (d / "Makefile").write_bytes(makefile(cfg, opts).replace("\n", "\r\n").encode("utf-8"))
        (d / "makedep.mk").write_bytes(makedep().replace("\n", "\r\n").encode("utf-8"))
        print(f"wrote {d / 'Makefile'}")


if __name__ == "__main__":
    main()
